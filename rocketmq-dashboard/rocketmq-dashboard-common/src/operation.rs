//! Non-secret ownership metadata captured when an application accepts an operation.

use std::fmt;

use serde::{Deserialize, Serialize};

use crate::EnvironmentId;

/// The trusted source of an operation's actor, resolved by the application service.
#[derive(Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(tag = "kind", rename_all = "snake_case")]
pub enum OperationActor {
    /// A locally authenticated operator. Forms do not choose this value.
    LocalOperator {
        /// Username from the established local session.
        username: String,
    },
    /// The local desktop when authentication is disabled.
    LocalDesktop,
    /// An application-owned maintenance task.
    System,
}

impl fmt::Debug for OperationActor {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter.write_str(match self {
            Self::LocalOperator { .. } => "LocalOperator",
            Self::LocalDesktop => "LocalDesktop",
            Self::System => "System",
        })
    }
}

/// A controlled resource identifier, never a request body, credential, or configuration dump.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(tag = "kind", content = "identity", rename_all = "snake_case")]
pub enum OperationResource {
    /// Local configuration and connection profiles.
    Configuration,
    /// The local desktop authentication session; never its password or token.
    LocalSession,
    /// A consumer group rule.
    Monitor(String),
    /// A Topic.
    Topic(String),
    /// A Consumer Group.
    ConsumerGroup(String),
    /// A Broker identity.
    Broker(String),
    /// An opaque message identifier.
    Message(String),
    /// An ACL subject.
    AclSubject(String),
}

/// Immutable attribution for an accepted operation.
///
/// The service creates this context once and retains its request ID through persistence retries.
/// A UI request epoch remains a separate, transient cancellation mechanism.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct OperationContext {
    /// Persistent data owner.
    pub environment_id: EnvironmentId,
    /// Connection generation captured at acceptance.
    pub configuration_revision: u64,
    /// Stable opaque operation identity, generated by the application.
    pub request_id: String,
    /// Trusted authentication or application actor.
    pub actor: OperationActor,
    /// Controlled resource affected by the operation.
    pub resource: OperationResource,
}
