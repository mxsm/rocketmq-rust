#[derive(Debug, Clone, Copy, Serialize, Deserialize, PartialEq, Eq)]
#[serde(rename_all = "camelCase")]
pub enum StorageBackend {
    File,
    Sqlite,
    #[serde(rename = "mysql")]
    MySql,
    #[serde(rename = "postgres")]
    Postgres,
}

impl StorageBackend {
    pub fn parse(value: &str) -> Result<Self, String> {
        match value.trim().to_ascii_lowercase().as_str() {
            "file" => Ok(Self::File),
            "sqlite" | "sqlite3" => Ok(Self::Sqlite),
            "mysql" => Ok(Self::MySql),
            "postgres" | "postgresql" => Ok(Self::Postgres),
            _ => Err(format!(
                "unsupported storage backend `{value}`; expected file, sqlite, mysql, or postgres"
            )),
        }
    }

    pub const fn as_str(self) -> &'static str {
        match self {
            Self::File => "file",
            Self::Sqlite => "sqlite",
            Self::MySql => "mysql",
            Self::Postgres => "postgres",
        }
    }

    pub const fn is_sql(self) -> bool {
        matches!(self, Self::Sqlite | Self::MySql | Self::Postgres)
    }
}

/// Persistent Environment identifier. Values are generated by the dashboard
/// and are opaque to HTTP clients.
#[derive(Debug, Clone, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(transparent)]
pub struct EnvironmentId(pub String);

impl EnvironmentId {
    pub fn new() -> Self {
        Self(Uuid::now_v7().to_string())
    }
}

impl Default for EnvironmentId {
    fn default() -> Self {
        Self::new()
    }
}

