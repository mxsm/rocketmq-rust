export function useSendLatencyMessages() {
  const english = useOperatorPreferences().locale === "en-US";
  const messages = english ? en : zh;
  return {
    ...messages,
    reason: (code: string) => Object.hasOwn(reasons, code)
      ? reasons[code as keyof typeof reasons][english ? 1 : 0]
      : messages.reasonUnknown,
  };
}
