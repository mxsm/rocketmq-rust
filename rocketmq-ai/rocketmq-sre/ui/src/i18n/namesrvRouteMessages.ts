export function useNamesrvRouteMessages() {
  const english = useOperatorPreferences().locale === "en-US";
  const messages = english ? en : zh;
  const lookup = (values: Record<string, readonly [string, string]>, code: string, fallback: string) =>
    Object.hasOwn(values, code) ? values[code][english ? 1 : 0] : fallback;
  return {
    ...messages,
    status: (code: string) => lookup(statuses, code, messages.unknown),
    dimension: (code: string) => lookup(dimensions, code, messages.dimensionUnknown),
    missing: (code: string) => lookup(missing, code, messages.unknown),
    reason: (code: string) => lookup(reasons, code, messages.reasonUnknown),
  };
}
